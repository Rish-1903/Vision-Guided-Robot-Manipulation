#!/usr/bin/env python3
"""Collect the latest run summaries into results/ (committed) as JSON + Markdown.

Usage: python tools/collect_results.py [--runs runs] [--out results]
Copies only small summary files, never images or scenes, and writes
results/RESULTS.md with one table per task for the report/slides.
"""
from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def latest(runs: Path, pattern: str):
    files = sorted(runs.glob(pattern), key=lambda f: f.stat().st_mtime, reverse=True)
    return files[0] if files else None


def pct(r):
    if not r or r.get('rate') is None:
        return 'n/a'
    return f"{100 * r['rate']:.1f}% ({r['successes']}/{r['n']}; 95% CI {100 * r['ci95_low']:.0f}-{100 * r['ci95_high']:.0f}%)"


def num(d, key='mean', fmt='{:.2f}'):
    return 'n/a' if not d or d.get(key) is None else fmt.format(d[key])


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--runs', type=Path, default=ROOT / 'runs')
    p.add_argument('--out', type=Path, default=ROOT / 'results')
    args = p.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    sources = {
        'task2_calibration': ('**/calibration_results/calibration_summary.json',
                              'stages/task2/dataset/calibration_results/calibration_summary.json'),
        'task2_selftest': (None, 'stages/task2/selftest_results.json'),
        'task2_render_checks': (None, 'stages/task2/render_checks/render_checks.json'),
        'task3_recovery': ('**/task3/recovered/recovery_results.json', None),
        'task4_localization': ('**/task4*/metrics.json', None),
        'task4_robustness': ('**/task4_robustness/robustness_summary.json', None),
        'task5_pose': ('**/task5*/metrics.json', None),
        'task6_benchmark': ('**/task6_benchmark_*/summary.json', None),
    }
    found = {}
    for name, (pattern, fixed) in sources.items():
        f = latest(args.runs, pattern) if pattern and args.runs.is_dir() else None
        if f is None and fixed and (ROOT / fixed).is_file():
            f = ROOT / fixed
        if f is not None:
            shutil.copy2(f, args.out / f'{name}.json')
            found[name] = (f, json.loads(f.read_text()))
            print(f'{name:<22} <- {f}')
        else:
            print(f'{name:<22}    (not found)')
    md = ['# Results', '', 'Generated by `tools/collect_results.py`. Raw copies of each summary JSON sit next to this file.', '']
    if 'task4_localization' in found:
        f, s = found['task4_localization']
        md += ['## Task 4: localization', f'Source: `{f.relative_to(ROOT) if f.is_relative_to(ROOT) else f}`', '',
               '| Metric | Value |', '|---|---|',
               f"| Detection rate | {pct(s.get('detection'))} |",
               f"| Centre error (px), mean / p95 | {num(s.get('center_error_px'))} / {num(s.get('center_error_px'), 'p95')} |",
               f"| BBox IoU, mean | {num(s.get('bbox_iou'), fmt='{:.3f}')} |", '']
    if 'task5_pose' in found:
        f, s = found['task5_pose']
        md += ['## Task 5: pose estimation', '', '| Metric | Value |', '|---|---|',
               f"| Pose rate | {pct(s.get('pose_estimation'))} |",
               f"| Translation error (mm), mean / p95 / max | {num(s.get('translation_error_mm'))} / "
               f"{num(s.get('translation_error_mm'), 'p95')} / {num(s.get('translation_error_mm'), 'max')} |",
               f"| Rotation error (deg, symmetry-aware), mean / max | {num(s.get('symmetry_rotation_error_deg'))} / "
               f"{num(s.get('symmetry_rotation_error_deg'), 'max')} |", '']
    if 'task4_robustness' in found:
        _, s = found['task4_robustness']
        md += ['## Tasks 4-5: robustness', '', '| Scenario | Detection | Pose | Median t-error (mm) | Gross (>20 mm) |',
               '|---|---|---|---|---|']
        for sc, r in s.items():
            gross = next((v for k, v in r.items() if k.startswith('gross')), 'n/a')
            md.append(f"| {sc} | {pct(r['detection'])} | {pct(r['pose'])} | "
                      f"{num(r['translation_error_mm'], 'median')} | {gross} |")
        md.append('')
    if 'task6_benchmark' in found:
        _, s = found['task6_benchmark']
        tol = s.get('tolerances', {})
        md += ['## Task 6: pick-and-place benchmark',
               f"{s.get('n_trials')} randomized layouts, {s.get('n_placements_attempted')} placements, "
               f"target source `{s.get('target_source')}`, injected extrinsic error {s.get('injected_extrinsic_error')}. "
               f"Success = XY < {tol.get('xy_mm')} mm, Z < {tol.get('z_mm')} mm, yaw < {tol.get('yaw_deg')} deg.", '',
               '| | Success | XY error mean / p95 / max (mm) | Yaw error mean (deg) |', '|---|---|---|---|']
        for loop in ('open_loop', 'closed_loop'):
            if loop in s:
                b = s[loop]
                md.append(f"| {loop.replace('_', ' ')} | {pct(b['success'])} | {num(b['xy_error_mm'])} / "
                          f"{num(b['xy_error_mm'], 'p95')} / {num(b['xy_error_mm'], 'max')} | {num(b['yaw_error_deg'])} |")
        md += ['', f"Failures by type: {s.get('failure_counts')}", '']
    if 'task2_selftest' in found:
        _, s = found['task2_selftest']
        md += ['## Task 2: synthetic calibration self-test', '', '| Profile | Noise (px) | Model | Mean fx error (%) | Std (%) |',
               '|---|---|---|---|---|']
        md += [f"| {r['profile']} | {r['noise_px']} | {r['model']} | {r['mean_fx_error_pct']:.3f} | {r['std_fx_error_pct']:.3f} |"
               for r in s['rows']]
        md.append('')
    if 'task2_render_checks' in found:
        _, s = found['task2_render_checks']
        md += ['## Task 2: render check', '', f"Measured fx {s['fx_measured_mean_px']:.1f} px, fy {s['fy_measured_mean_px']:.1f} px; "
               f"nominal {s['f_if_angle_on_long_axis_px']:.1f} px. Verdict: {s['verdict']}", '']
    (args.out / 'RESULTS.md').write_text('\n'.join(md) + '\n')
    print('Wrote', args.out / 'RESULTS.md')


if __name__ == '__main__':
    main()
